/**
 * cleanTitle.ts — очистка названий от накопленных суффиксов качества.
 *
 * Проблема: заголовок просмотра собирался как `Название (4K)` и сохранялся
 * в Историю; при повторном просмотре из Истории суффикс добавлялся ещё раз —
 * «Название (4K) (4K) (4K)…». Здесь суффиксы качества/формата срезаются в
 * любом виде и в любом количестве: «Название (4K) (4K) [VK 4K]» → «Название».
 * Год «(2021)» и прочие скобки без слов качества не затрагиваются.
 */

const QUALITY_WORD = /(?:4k|2160p|uhd|1080p|fhd|720p|\bhd\b|480p|\bsd\b)/i;

export function stripQualitySuffixes(title: string): string {
  return String(title || '')
    .replace(new RegExp(`\\s*\\([^()]*${QUALITY_WORD.source}[^()]*\\)`, 'gi'), ' ')
    .replace(new RegExp(`\\s*\\[[^\\[\\]]*${QUALITY_WORD.source}[^\\[\\]]*\\]`, 'gi'), ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
